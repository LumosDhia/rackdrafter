import { slugify } from '../lib/determinism.ts';
import { canonicalJson } from '../domain/canonical.ts';
import type { Project } from '../domain/types.ts';
import type { GeneratedFile } from '../analysis/types.ts';

const HEADER = (name: string) => `# Generated by RackDrafter from project "${name}". Do not edit by hand.`;

export function generateJson(project: Project): GeneratedFile[] {
  return [
    {
      path: `project/${slugify(project.name)}.rackdrafter.json`,
      content: `${JSON.stringify(JSON.parse(canonicalJson(project)), null, 2)}\n`,
      mime: 'application/json',
    },
  ];
}

export function generateMermaid(project: Project): GeneratedFile[] {
  const lines = [HEADER(project.name), '', 'flowchart LR'];
  for (const n of [...project.nodes].sort((a, b) => a.id.localeCompare(b.id))) {
    const label = n.label.replace(/"/g, '#quot;');
    lines.push(`  ${n.id}["${label}"]`);
  }
  for (const l of [...project.links].sort((a, b) => a.id.localeCompare(b.id))) {
    lines.push(`  ${l.source} --> ${l.target}`);
  }
  lines.push('');
  return [
    {
      path: 'diagram/topology.mmd',
      content: `${lines.join('\n')}`,
      mime: 'text/plain',
    },
  ];
}

export function generateIpTable(project: Project): GeneratedFile[] {
  const rows: { ip: string; host: string; nic: string }[] = [];
  for (const n of project.nodes) {
    if (n.kind !== 'device') continue;
    for (const nic of n.spec.nics) {
      if (nic.ip) rows.push({ ip: nic.ip, host: n.label, nic: nic.name });
    }
  }
  rows.sort((a, b) =>
    a.ip.split('.').map(Number).join('.').localeCompare(b.ip.split('.').map(Number).join('.')),
  );
  const lines = [
    HEADER(project.name),
    '',
    '| IP | Host | NIC |',
    '| --- | --- | --- |',
    ...rows.map((r) => `| ${r.ip} | ${r.host} | ${r.nic} |`),
    '',
  ];
  return [{ path: 'network/ip-plan.md', content: lines.join('\n'), mime: 'text/markdown' }];
}

export function generateCompose(project: Project): GeneratedFile[] {
  const files: GeneratedFile[] = [];
  for (const n of project.nodes) {
    if (n.kind !== 'device') continue;
    const services = project.nodes.filter(
      (s): s is Extract<typeof s, { kind: 'service' }> =>
        s.kind === 'service' &&
        s.placement.kind === 'host' &&
        s.placement.hostId === n.id &&
        s.spec.runtime === 'docker',
    );
    if (services.length === 0) continue;
    const hostSlug = slugify(n.spec.hostname || n.label);
    const svcLines: string[] = [];
    const sorted = [...services].sort((a, b) => slugify(a.label).localeCompare(slugify(b.label)));
    for (const s of sorted) {
      const key = slugify(s.label);
      svcLines.push(`  ${key}:`);
      if (s.spec.image) svcLines.push(`    image: ${s.spec.image}`);
    }
    const body = [HEADER(project.name), `name: ${hostSlug}`, 'services:', ...svcLines, ''].join('\n');
    files.push({
      path: `compose/${hostSlug}/compose.yaml`,
      content: body,
      mime: 'text/yaml',
    });
  }
  files.sort((a, b) => a.path.localeCompare(b.path));
  return files;
}

export function generateK8s(project: Project): GeneratedFile[] {
  const files: GeneratedFile[] = [];
  for (const c of [...project.clusters].sort((a, b) => a.name.localeCompare(b.name))) {
    const ns = [...c.namespaces].sort();
    const docs = ns.map((n) => `apiVersion: v1\nkind: Namespace\nmetadata:\n  name: ${n}\n`).join('---\n');
    files.push({
      path: `k8s/${slugify(c.name)}/namespaces.yaml`,
      content: `${HEADER(project.name)}\n${docs}`,
      mime: 'text/yaml',
    });
  }
  files.sort((a, b) => a.path.localeCompare(b.path));
  return files;
}

export type ExportFormat = 'compose' | 'k8s' | 'ip-table' | 'mermaid' | 'json';

export function generateAll(project: Project, format: ExportFormat): GeneratedFile[] {
  switch (format) {
    case 'json':
      return generateJson(project);
    case 'mermaid':
      return generateMermaid(project);
    case 'ip-table':
      return generateIpTable(project);
    case 'compose':
      return generateCompose(project);
    case 'k8s':
      return generateK8s(project);
  }
}
