const TABLER_DIR = join(process.cwd(), 'node_modules/@tabler/icons/icons/outline');

/** Converts circle/rect/line/polyline/polygon/ellipse to path data so the renderer only needs `<path>`. */
function toPath(el: string): string | null {
  const attr = (name: string, dflt = 0): number => {
    const m = new RegExp(`${name}\\s*=\\s*"([^"]+)"`).exec(el);
    if (!m) return dflt;
    const v = Number.parseFloat(m[1] ?? '');
    return Number.isFinite(v) ? v : dflt;
  };
  const tag = /^<\s*([a-zA-Z]+)/.exec(el.trim())?.[1]?.toLowerCase() ?? '';
  const f = (n: number): string => (Math.round(n * 1000) / 1000).toString();
  switch (tag) {
    case 'path': {
      const d = /d\s*=\s*"([^"]+)"/.exec(el)?.[1];
      return d ?? null;
    }
    case 'line':
      return `M${f(attr('x1'))} ${f(attr('y1'))}L${f(attr('x2'))} ${f(attr('y2'))}`;
    case 'circle': {
      const cx = attr('cx');
      const cy = attr('cy');
      const r = attr('r');
      return `M${f(cx - r)} ${f(cy)}a${f(r)} ${f(r)} 0 1 0 ${f(r * 2)} 0a${f(r)} ${f(r)} 0 1 0 ${f(-r * 2)} 0`;
    }
    case 'ellipse': {
      const cx = attr('cx');
      const cy = attr('cy');
      const rx = attr('rx');
      const ry = attr('ry');
      return `M${f(cx - rx)} ${f(cy)}a${f(rx)} ${f(ry)} 0 1 0 ${f(rx * 2)} 0a${f(rx)} ${f(ry)} 0 1 0 ${f(-rx * 2)} 0`;
    }
    case 'rect': {
      const x = attr('x');
      const y = attr('y');
      const w = attr('width');
      const h = attr('height');
      const r = Math.min(attr('rx'), w / 2, h / 2);
      return `M${f(x + r)} ${f(y)}h${f(w - 2 * r)}a${f(r)} ${f(r)} 0 0 1 ${f(r)} ${f(r)}v${f(h - 2 * r)}a${f(r)} ${f(r)} 0 0 1 ${f(-r)} ${f(r)}h${f(-(w - 2 * r))}a${f(r)} ${f(r)} 0 0 1 ${f(-r)} ${f(-r)}v${f(-(h - 2 * r))}a${f(r)} ${f(r)} 0 0 1 ${f(r)} ${f(-r)}z`;
    }
    case 'polyline':
    case 'polygon': {
      const pts = (/points\s*=\s*"([^"]+)"/.exec(el)?.[1] ?? '').trim().split(/\s+/).filter(Boolean);
      if (pts.length < 2) return null;
      const [x0, y0] = pts[0]?.split(',') ?? [];
      const rest = pts.slice(1).map((p) => {
        const [x, y] = p.split(',');
        return `L${f(Number(x))} ${f(Number(y))}`;
      });
      return `M${f(Number(x0))} ${f(Number(y0))}${rest.join('')}${tag === 'polygon' ? 'z' : ''}`;
    }
    default:
      return null;
  }
}

function readGlyph(name: string): string[] | null {
  const file = join(TABLER_DIR, `${name}.svg`);
  if (!existsSync(file)) return null;
  const svg = readFileSync(file, 'utf8');
  const body = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '');
  const elements = body.match(/<(path|circle|rect|line|polyline|polygon|ellipse)\b[^>]*\/?>/g) ?? [];
  const paths: string[] = [];
  for (const el of elements) {
    // Tabler's transparent hit-area rectangle: `stroke="none" d="M0 0h24v24H0z"`.
    if (/stroke\s*=\s*"none"/.test(el)) continue;
    const d = toPath(el);
    if (d) paths.push(d);
  }
  return paths.length > 0 ? paths : null;
}

function main(): void {
  const names = new Set<string>([...catalogGlyphs(), ...Object.values(CATEGORY_GLYPH), ...UI_GLYPHS]);
  for (const key of Object.keys(HAND_WRITTEN)) names.add(key);

  const out: Record<string, string[]> = {};
  const missing: string[] = [];
  for (const name of [...names].sort()) {
    const paths = readGlyph(name);
    if (paths) out[name] = paths;
    else missing.push(name);
  }

  const banner = `// GENERATED by scripts/icons/build-glyphs.ts from @tabler/icons (MIT) — do not edit by hand.\n// ${Object.keys(out).length} glyphs. Re-run \`npm run icons:fetch\` to refresh.\n\n`;
  const literal = `export const TABLER_GLYPHS: Record<string, string[]> = ${JSON.stringify(out, null, 2)};\n`;
  writeFileSync(join(process.cwd(), 'src/client/ui/glyphs.generated.ts'), banner + literal);

  console.log(`glyphs: ${Object.keys(out).length} generated`);
  if (missing.length > 0) console.warn(`glyphs missing from @tabler/icons: ${missing.join(', ')}`);
}

main();
